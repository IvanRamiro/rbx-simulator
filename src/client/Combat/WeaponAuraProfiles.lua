-- A weapon's blade as a list of stations, foot to point: { z, cx, cy, hw, ht, along } where `along` is the distance
-- along the blade (studs) from the first station, and the last station is the point itself.
local cache = {}
function P.blade(weaponId)
    local blade = cache[weaponId]
    if blade then
        return blade
    end
    local m = P.Measured[weaponId]
    if not m then
        return nil
    end
    blade = {}
    local along, prev = 0, nil
    for _, s in m[1] do
        local station = { s[1], s[2], s[3], s[4], s[5], 0 }
        if prev then
            along += math.sqrt((s[1] - prev[1]) ^ 2 + (s[2] - prev[2]) ^ 2 + (s[3] - prev[3]) ^ 2)
        end
        station[6] = along
        table.insert(blade, station)
        prev = s
    end
    local tip = m.Tip
    along += math.sqrt((tip.Z - prev[1]) ^ 2 + (tip.X - prev[2]) ^ 2 + (tip.Y - prev[3]) ^ 2)
    table.insert(blade, { tip.Z, tip.X, tip.Y, 0, 0.02, along })
    blade.Length = along
    cache[weaponId] = blade
    return blade
end

return P
