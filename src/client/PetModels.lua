-- What each pet companion looks like: small, original low-poly models built
-- from plain parts when needed (no uploaded meshes). Purely visual.
--
-- The low-poly look comes from flat-faced shapes only (no smooth spheres):
-- faceted octagonal "prisms" for bodies and heads, wedges for ears, beaks,
-- wings and tails, and small blocks for eyes and details.
--
-- Each pet is a list of pieces around the pet's centre, facing -Z (forward),
-- with +Y up and +X to the pet's right.
--   Shape         "Prism" (octagonal prism, built from 2 blocks and 4 corner
--                 wedges), "Block", "Wedge" or "CornerWedge"
--   Axis          For prisms: "X", "Y" or "Z", the direction the prism runs
--                 along (default "Z", front to back)
--   Size          Size in studs, before the pet's Scale
--   At            Position and rotation relative to the pet's centre
--   Color         Colour of the piece
--   Neon          Glows (for eyes, flames, energy)
--   Flat          Prisms only: skip the lighter top / darker bottom facet shading
--   Glass         Slightly see-through glassy surface (for water)
--   Transparency  0 to 1 (optional)
-- Scale makes the whole pet bigger or smaller (rarer pets are a little larger).
--
-- Uploaded meshes: a MeshPart named after the pet ID in
-- ReplicatedStorage.PetMeshes is used as the pet's body instead of the
-- part-built design, dressed up with a glowing energy shell, eyes and its
-- element's effects (MESH_LOOKS below). Set its look in Studio (Color,
-- Material, TextureID); these attributes adjust it:
--   Turn          CFrame rotation that stands the mesh up and faces it to -Z
--   Scale         Size multiplier (on top of the pet's Scale below)
--   GlowColor     Colour of the energy shell and effects
--   EyePosition   Where the right eye sits (measured on the mesh in Studio)
--   EyeSize       Eye diameter (default 0.2), smaller for narrow faces
--   TailPosition  Tip of the tail, TopPosition  top of the head (for effects)
-- Positions are in studs for the mesh at its uploaded size, facing -Z.
--
-- Which look a pet gets, best first:
-- 1. Imported Blender model: a Model named after the pet ID in PetMeshes,
--    imported from assets/pets/<PetId>.fbx with the 3D Importer (addImported).
--    Pets exported with --rig come in separate parts and are animated (PetRig).
-- 2. Runtime Blender mesh: ReplicatedStorage.PetMeshData.<PetId> holds the
--    same pet as triangles (generated by tools/blender/export_pet.py), built
--    into MeshParts with EditableMesh (requestBlenderMesh). Needs "Allow Mesh /
--    Image APIs", and a device only has mesh memory for a couple of pets, so
--    this is a backup until a pet's model is imported.
-- 3. The uploaded MeshPart named after the pet ID in PetMeshes (addMesh).
-- 4. The part-built design below.
-- Blender pets get a facet-coloured body plus Neon glow parts, dressed with
-- an energy shell, a light and the element's particles (dressUp).

