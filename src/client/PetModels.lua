local PART_SHAPES = {
    Block = Enum.PartType.Block,
    Wedge = Enum.PartType.Wedge,
    CornerWedge = Enum.PartType.CornerWedge,
}

-- Prisms are built along their local X axis; these turn X to the chosen axis
local PRISM_TURNS = {
    X = CFrame.identity,
    Y = CFrame.Angles(0, 0, math.rad(90)),
    Z = CFrame.Angles(0, math.rad(90), 0),
}

-- The pieces of an octagonal prism with the given size, as { Shape, Size,
-- Offset }: a plus shape of two blocks, with a wedge filling each of its four
-- corners to make the 45-degree facets (checked in Studio)
local function prismPieces(size, axis)
    -- Length along the prism, then its cross-section, in the prism's own frame
    local length, height, depth
    if axis == "X" then
        length, height, depth = size.X, size.Y, size.Z
    elseif axis == "Y" then
        length, height, depth = size.Y, size.X, size.Z
    else
        length, height, depth = size.Z, size.Y, size.X
    end

    local turn = PRISM_TURNS[axis]
    local corner = math.min(height, depth) * 0.293 -- Makes a regular octagon when height = depth
    local pieces = {
        { Shape = "Block", Size = Vector3.new(length, height - 2 * corner, depth), Offset = turn, Tone = 0 },
        { Shape = "Block", Size = Vector3.new(length, height, depth - 2 * corner), Offset = turn, Tone = 0 },
    }
    for index, signs in { { 1, 1 }, { -1, 1 }, { -1, -1 }, { 1, -1 } } do
        -- Facets on the prism's "top" side are lit, the others shaded
        table.insert(pieces, {
            Shape = "Wedge",
            Tone = signs[1],
            Size = Vector3.new(length, corner, corner),
            Offset = turn
                * CFrame.new(0, signs[1] * (height / 2 - corner / 2), signs[2] * (depth / 2 - corner / 2))
                * CFrame.Angles(math.rad(90 * (index - 1)), 0, 0)
                * CFrame.Angles(0, math.pi, 0),
        })
    end
    return pieces
end

-- Lighter (tone 1) or darker (tone -1) versions of a colour, so the facets of
-- a prism shade like cut crystal
local function toneColor(color, tone)
    if tone > 0 then
        return color:Lerp(Color3.new(1, 1, 1), 0.22)
    elseif tone < 0 then
        return color:Lerp(Color3.new(0, 0, 0), 0.22)
    end
    return color
end

local function createPart(model, rootPart, shape, size, cframe, spec, tone)
    local part = Instance.new("Part")
    part.Shape = PART_SHAPES[shape]
    part.Size = size
    part.CFrame = cframe
    part.Color = if spec.Neon or spec.Flat then spec.Color else toneColor(spec.Color, tone or 0)
    part.Material = if spec.Neon then Enum.Material.Neon elseif spec.Glass then Enum.Material.Glass else Enum.Material.SmoothPlastic
    part.Transparency = spec.Transparency or 0
    part.TopSurface = Enum.SurfaceType.Smooth
    part.BottomSurface = Enum.SurfaceType.Smooth
    -- Visual only: never collides, triggers touches, blocks raycasts or casts shadows
    part.CanCollide = false
    part.CanTouch = false
    part.CanQuery = false
    part.CastShadow = false
    part.Massless = true
    part.Anchored = false

    -- Welded to the root, so moving the root moves the whole pet
    local weld = Instance.new("WeldConstraint")
    weld.Part0 = rootPart
    weld.Part1 = part
    weld.Parent = part

    part.Parent = model
end

