local function weldTo(rootPart, part)
    part.Anchored = false
    part.CanCollide = false
    part.CanTouch = false
    part.CanQuery = false
    part.CastShadow = false
    part.Massless = true
    local weld = Instance.new("WeldConstraint")
    weld.Part0 = rootPart
    weld.Part1 = part
    weld.Parent = part
end

-- A plain part in pet space (the root sits at the origin facing -Z)
local function addAccent(model, rootPart, shape, size, cframe, color, neon)
    local part = Instance.new("Part")
    part.Shape = shape
    part.Size = size
    part.CFrame = cframe
    part.Color = color
    part.Material = if neon then Enum.Material.Neon else Enum.Material.SmoothPlastic
    part.TopSurface = Enum.SurfaceType.Smooth
    part.BottomSurface = Enum.SurfaceType.Smooth
    weldTo(rootPart, part)
    part.Parent = model
    return part
end

-- Builds a pet from its uploaded mesh (see the top of this file)
local function addMesh(model, rootPart, template, design, petId)
    local k = (template:GetAttribute("Scale") or 1) * design.Scale * PetModels.SIZE
    local turn = template:GetAttribute("Turn") or CFrame.identity
    local look = MESH_LOOKS[petId] or { Eyes = NAVY }
    local glow = template:GetAttribute("GlowColor")
    glow = if typeof(glow) == "Color3" then glow else template.Color
    local function point(name, fallback)
        local value = template:GetAttribute(name)
        return (if typeof(value) == "Vector3" then value else fallback) * k
    end

    local body = template:Clone()
    body.Size = template.Size * k
    body.CFrame = turn
    weldTo(rootPart, body)
    body.Parent = model

    -- A shimmering energy shell just outside the body
    local shell = template:Clone()
    shell.Name = "EnergyShell"
    shell.Material = Enum.Material.ForceField
    shell.Color = glow
    shell.TextureID = ""
    shell.Size = body.Size * 1.07
    shell.CFrame = turn
    weldTo(rootPart, shell)
    shell.Parent = model

    -- Round glossy eyes with a highlight, facing forward
    local eye = point("EyePosition", Vector3.new(0.13, 0.3, -0.9))
    local eyeSize = (template:GetAttribute("EyeSize") or 0.2) * k
    for _, side in { -1, 1 } do
        local center = CFrame.new(eye.X * side, eye.Y, eye.Z)
        addAccent(model, rootPart, Enum.PartType.Cylinder, Vector3.new(0.04 * k, eyeSize, eyeSize),
            center * CFrame.Angles(0, math.rad(90), 0), look.Eyes, look.GlowEyes)
        addAccent(model, rootPart, Enum.PartType.Cylinder, Vector3.new(0.03 * k, eyeSize * 0.4, eyeSize * 0.4),
            center * CFrame.new(-0.03 * k * side, 0.04 * k, -0.025 * k) * CFrame.Angles(0, math.rad(90), 0), Color3.new(1, 1, 1), true)
    end

    -- Floating pieces above the head
    local top = point("TopPosition", Vector3.new(0, 0.7, -0.5))
    if look.Gems then
        for _, side in { -1, 1 } do
            addAccent(model, rootPart, Enum.PartType.Block, Vector3.one * 0.14 * k,
                CFrame.new(top + Vector3.new(0.3 * k * side, 0.3 * k, 0)) * CFrame.Angles(math.rad(45), 0, math.rad(45)), glow, true)
        end
    end
    if look.Orb then
        local orbCenter = CFrame.new(top + Vector3.new(0.45 * k, 0.55 * k, 0.4 * k))
        addAccent(model, rootPart, Enum.PartType.Ball, Vector3.one * 0.3 * k, orbCenter, glow, true)
        for index = 0, 9 do
            local angle = index / 10 * 2 * math.pi
            addAccent(model, rootPart, Enum.PartType.Block, Vector3.new(0.05, 0.04, 0.2) * k,
                orbCenter * CFrame.Angles(math.rad(20), 0, math.rad(-15))
                    * CFrame.new(math.cos(angle) * 0.36 * k, 0, math.sin(angle) * 0.36 * k)
                    * CFrame.Angles(0, -angle, 0), glow, true)
        end
    end

    -- The element's particles
    local effect = MESH_EFFECTS[look.Effect]
    if effect then
        local tail = Instance.new("Attachment")
        tail.Name = "TailTip"
        tail.Position = point("TailPosition", Vector3.new(0, 0, 1))
        tail.Parent = rootPart
        effect(body, tail, glow, k)
    end
end

-- Builds a pet from its Blender model (tools/blender/build_pets.py), imported
-- with Studio's 3D Importer as a Model named after the pet. Its "<PetId>_Body"
-- keeps the palette texture; "<PetId>_Glow_<rrggbb>" pieces become Neon in
-- that colour. The aura is a shimmering shell, a soft light and the
-- element's particles. An optional Turn attribute on the Model re-aims it.
local dressUp -- Defined after addImported

local function addImported(model, rootPart, template, design, petId)
    local look = MESH_LOOKS[petId] or {}
    local turn = template:GetAttribute("Turn") or CFrame.identity
    local boxCFrame, boxSize = template:GetBoundingBox()
    local longest = math.max(boxSize.X, boxSize.Y, boxSize.Z)
    local k = design.Scale * PetModels.SIZE
    -- Sized in studs as in Blender units, whatever units the importer used
    local scale = (look.Length or longest) * k / longest

    -- Animated pets come in separate parts joined by Motor6Ds (PetRig)
    if PetRig.isRigged(petId, template) then
        local function place(piece)
            local offset = CFrame.new(-boxCFrame.Position) * piece.CFrame
            return turn * (offset.Rotation + offset.Position * scale), piece.Size * scale
        end
        rigs[model] = PetRig.build(model, rootPart, template, petId, place, scale)
        return
    end

    local body
    for _, piece in template:GetDescendants() do
        if not piece:IsA("BasePart") then
            continue
        end
        local part = piece:Clone()
        local hex = string.match(piece.Name, "_Glow_(%x%x%x%x%x%x)$")
        for _, child in part:GetChildren() do
            -- The importer may put the palette texture in a SurfaceAppearance; keep it on the body
            if hex or not child:IsA("SurfaceAppearance") then
                child:Destroy()
            end
        end
        local offset = CFrame.new(-boxCFrame.Position) * piece.CFrame
        part.Size = piece.Size * scale
        part.CFrame = turn * (offset.Rotation + offset.Position * scale)
        if hex then
            part.Color = Color3.fromHex(hex)
            part.Material = Enum.Material.Neon
            if part:IsA("MeshPart") then
                part.TextureID = ""
            end
        else
            part.Material = Enum.Material.SmoothPlastic
            body = body or part
        end
        weldTo(rootPart, part)
        part.Parent = model
    end
    if body then
        dressUp(model, rootPart, body, boxSize * scale, look, k, turn)
    end
end

-- The aura around a meshed pet: a shimmering energy shell just outside the
-- body, a soft light and the element's particles. `size` is the whole pet's
-- size in studs.
dressUp = function(model, rootPart, body, size, look, k, turn)
    local glow = look.Glow or Color3.new(1, 1, 1)
    local shell = body:Clone()
    shell.Name = "EnergyShell"
    shell:ClearAllChildren()
    shell.Material = Enum.Material.ForceField
    shell.Color = glow
    if shell:IsA("MeshPart") then
        shell.TextureID = ""
    end
    shell.Size = body.Size * 1.06
    weldTo(rootPart, shell)
    shell.Parent = model

    local light = Instance.new("PointLight")
    light.Color = glow
    light.Brightness = 1.2
    light.Range = 3 * k
    light.Parent = body

    -- The element's particles; the tail tip is about the top of the back
    local effect = MESH_EFFECTS[look.Effect]
    if effect then
        local tail = Instance.new("Attachment")
        tail.Name = "TailTip"
        tail.Position = (turn or CFrame.identity) * Vector3.new(0, size.Y * 0.25, size.Z * 0.45)
        tail.Parent = rootPart
        effect(body, tail, glow, k)
    end
end

-- Builds one MeshPart from a part of a pet's triangle data (see the top of
-- this file). Every triangle gets its own normal, so each facet is shaded on
-- its own like cut crystal. Returns the part and its centre in pet space.
local function buildMeshPart(spec)
    local mesh = AssetService:CreateEditableMesh()
    local positions, faces = spec.Positions, spec.Faces
    local vertexIds = table.create(#positions // 3)
    local low, high = Vector3.one * math.huge, -Vector3.one * math.huge
    for i = 1, #positions, 3 do
        local position = Vector3.new(positions[i], positions[i + 1], positions[i + 2])
        low, high = low:Min(position), high:Max(position)
        table.insert(vertexIds, mesh:AddVertex(position))
    end

    local colorIds = {}
    for index, hex in spec.Colors or {} do
        colorIds[index] = mesh:AddColor(Color3.fromHex(hex), 1)
    end

    for f = 1, #faces, 3 do
        local a, b, c = vertexIds[faces[f]], vertexIds[faces[f + 1]], vertexIds[faces[f + 2]]
        local cross = (mesh:GetPosition(b) - mesh:GetPosition(a)):Cross(mesh:GetPosition(c) - mesh:GetPosition(a))
        if cross.Magnitude < 1e-9 then
            continue -- Degenerate sliver; nothing to draw
        end
        local faceId = mesh:AddTriangle(a, b, c)
        local normal = mesh:AddNormal(cross.Unit)
        mesh:SetFaceNormals(faceId, { normal, normal, normal })
        if spec.FaceColors then
            local color = colorIds[spec.FaceColors[(f + 2) // 3]]
            mesh:SetFaceColors(faceId, { color, color, color })
        end
    end

    local part = AssetService:CreateMeshPartAsync(Content.fromObject(mesh), {
        CollisionFidelity = Enum.CollisionFidelity.Box,
    })
    part.Name = spec.Name
    if spec.Glow then
        part.Color = Color3.fromHex(spec.Glow)
        part.Material = Enum.Material.Neon
    else
        part.Color = Color3.new(1, 1, 1) -- Let the facet colours show as they are
        part.Material = Enum.Material.SmoothPlastic
    end
    return part, (low + high) / 2, low, high
end

-- The mesh API has to be allowed for the experience (Game Settings >
-- Security > "Allow Mesh / Image APIs"). When it isn't, Roblox still hands
-- back MeshParts but draws them as pink checkerboards, only warning in the
-- output, so a tiny test mesh is built first and the warning looked for.
local BLOCKED_WARNING = "EditableMesh is not accessible"
local function meshApiWorks()
    -- The warning arrives a moment after the mesh is made, so listen for it
    local blocked = false
    local listener = LogService.MessageOut:Connect(function(message)
        if string.find(message, BLOCKED_WARNING, 1, true) then
            blocked = true
        end
    end)
    local ok, works = pcall(function()
        local mesh = AssetService:CreateEditableMesh()
        if not mesh then
            return false -- Blocked, or over the device's memory budget
        end
        local a = mesh:AddVertex(Vector3.zero)
        local b = mesh:AddVertex(Vector3.xAxis)
        local c = mesh:AddVertex(Vector3.yAxis)
        mesh:AddTriangle(a, b, c)
        AssetService:CreateMeshPartAsync(Content.fromObject(mesh)):Destroy()
        mesh:Destroy()
        task.wait(0.5)
        return not blocked
    end)
    listener:Disconnect()
    if not (ok and works) then
        warn("PetModels: the mesh API isn't available here, so pets keep their older look."
            .. " Allow it in Game Settings > Security > Allow Mesh / Image APIs.")
        return false
    end
    return true
end

-- Runtime meshes are a backup for pets that have no imported model yet: the
-- device's mesh memory only fits a couple of pets, so each one is built in
-- the background only when it's first shown. Until it's ready the pet uses its
-- older look; PetModels.Version goes up when it is, so callers can rebuild.
local meshApiState = nil -- nil = not checked yet, then true / false
local requested = {}

local function requestBlenderMesh(petId)
    local module = meshDataFolder and meshDataFolder:FindFirstChild(petId)
    if requested[petId] or not module or meshApiState == false then
        return
    end
    requested[petId] = true
    task.spawn(function()
        if meshApiState == nil then
            meshApiState = meshApiWorks()
        end
        if not meshApiState then
            return
        end
        local ok, result = pcall(function()
            local entry = { parts = {} }
            local low, high = Vector3.one * math.huge, -Vector3.one * math.huge
            for _, spec in require(module) do
                local part, center, partLow, partHigh = buildMeshPart(spec)
                low, high = low:Min(partLow), high:Max(partHigh)
                table.insert(entry.parts, { part = part, center = center, glow = spec.Glow ~= nil })
            end
            entry.size = high - low
            return entry
        end)
        if ok then
            blenderMeshes[petId] = result
            PetModels.Version += 1
        else
            warn("PetModels: couldn't build the " .. petId .. " mesh, using its older look: " .. tostring(result))
        end
    end)
end

-- Builds a pet from its Blender mesh (already loaded)
local function addBlender(model, rootPart, mesh, design, petId)
    local look = MESH_LOOKS[petId] or {}
    local k = design.Scale * PetModels.SIZE
    local body
    for _, piece in mesh.parts do
        local part = piece.part:Clone()
        part.Size = piece.part.Size * k
        part.CFrame = CFrame.new(piece.center * k)
        weldTo(rootPart, part)
        part.Parent = model
        if not piece.glow then
            body = body or part
        end
    end
    if body then
        dressUp(model, rootPart, body, mesh.size * k, look, k)
    end
end

-- Builds a pet's model (not yet parented) around an invisible anchored root
-- part at the origin. Every piece is welded to the root, so the caller moves
-- the whole pet by moving just the root (for example with BulkMoveTo).
-- Parent the model BEFORE moving the root: each weld locks in its piece's
-- offset when it activates, so moving the root first would leave the pieces
-- behind at the origin (checked in Studio).
-- Returns the model and its root part, or nil for an unknown pet.
function PetModels.build(petId)
    local design = PetModels.Pets[petId]
    if not design then
        return nil
    end

    local model = Instance.new("Model")
    model.Name = petId

    local rootPart = Instance.new("Part")
    rootPart.Name = "Root"
    rootPart.Size = Vector3.new(0.2, 0.2, 0.2)
    rootPart.Transparency = 1
    rootPart.Anchored = true
    rootPart.CanCollide = false
    rootPart.CanTouch = false
    rootPart.CanQuery = false
    rootPart.CFrame = CFrame.identity
    rootPart.Parent = model
    model.PrimaryPart = rootPart

    -- Imported Blender model > runtime Blender mesh > uploaded MeshPart > parts
    local imported, meshTemplate
    for _, child in if meshFolder then meshFolder:GetChildren() else {} do
        if child.Name == petId then
            if child:IsA("Model") then
                imported = child
            elseif child:IsA("MeshPart") then
                meshTemplate = child
            end
        end
    end
    if imported then
        addImported(model, rootPart, imported, design, petId)
        return model, rootPart
    end
    local blender = blenderMeshes[petId]
    if blender then
        addBlender(model, rootPart, blender, design, petId)
        return model, rootPart
    end
    requestBlenderMesh(petId)
    if meshTemplate then
        addMesh(model, rootPart, meshTemplate, design, petId)
        return model, rootPart
    end

    local scale = design.Scale * PetModels.SIZE
    for _, spec in design.Parts do
        local offset = spec.At - spec.At.Position + spec.At.Position * scale
        local size = spec.Size * scale

        if spec.Shape == "Prism" then
            for _, piece in prismPieces(size, spec.Axis or "Z") do
                createPart(model, rootPart, piece.Shape, piece.Size, offset * piece.Offset, spec, piece.Tone)
            end
        else
            createPart(model, rootPart, spec.Shape, size, offset, spec)
        end
    end

    return model, rootPart
end

-- Catch config mistakes as soon as the game starts
for petId in GameConfig.Pets do
    assert(PetModels.Pets[petId], "PetModels has no model for pet " .. petId)
end

for petId, design in PetModels.Pets do
    for _, spec in design.Parts do
        assert(spec.Shape == "Prism" or PART_SHAPES[spec.Shape], "PetModels: " .. petId .. " uses an unknown Shape: " .. tostring(spec.Shape))
        assert(spec.Shape ~= "Prism" or PRISM_TURNS[spec.Axis or "Z"], "PetModels: " .. petId .. " has a prism with an unknown Axis")
    end
end

return PetModels
