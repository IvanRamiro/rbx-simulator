"""Writes the Realm 6 Studio build kit from tools/vfx/realm6_elements.py (the one place every number lives):

    python3 tools/vfx/realm6_build_luau.py

    tools/roblox/realm6/build_<element>.lua   one per element: run in Studio's command bar (Edit). It builds that element's
                                              Attachments, Beams, ParticleEmitters and Trails on the AuraWorkbench dummy's
                                              HumanoidRootPart (replacing its earlier ones, by name prefix). Authored once
                                              in Studio and saved with the place: nothing is generated at runtime.
    tools/roblox/realm6/build_all.lua         every element in order
    src/client/Auras/Realm6MotionConfig.lua   the paths Realm6Motion moves the trail attachments along (the vortex
                                              comets), so the preview, the build and the game agree

A texture with no asset id yet (TEXTURES[...][1] is None) is written as rbxassetid://0 and the build script stops before
touching anything: upload it (after the owner approves the image), put the id in realm6_elements.TEXTURES, rerun this.
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import realm6_elements as E  # noqa: E402

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..")
OUT = os.path.join(ROOT, "tools", "roblox", "realm6")
MOTION = os.path.join(ROOT, "src", "client", "Auras", "Realm6MotionConfig.lua")


def num(x):
    if isinstance(x, bool):
        return "true" if x else "false"
    if isinstance(x, int):
        return str(x)
    return ("%.4f" % x).rstrip("0").rstrip(".") if abs(x - round(x)) > 1e-9 else str(int(round(x)))


def value(v):
    if isinstance(v, (bool, int, float)):
        return num(v)
    if isinstance(v, str):
        return '"%s"' % v
    tag = v[0]
    if tag == "CS":
        return "ColorSequence.new({ %s })" % ", ".join(
            "ColorSequenceKeypoint.new(%s, Color3.fromRGB(%d, %d, %d))" % (num(t), c[0], c[1], c[2]) for t, c in v[1])
    if tag == "NS":
        return "NumberSequence.new({ %s })" % ", ".join(
            "NumberSequenceKeypoint.new(%s)" % ", ".join(num(x) for x in k) for k in v[1])
    if tag == "NR":
        return "NumberRange.new(%s, %s)" % (num(v[1]), num(v[2]))
    if tag == "V2":
        return "Vector2.new(%s, %s)" % (num(v[1]), num(v[2]))
    if tag == "V3":
        return "Vector3.new(%s, %s, %s)" % (num(v[1]), num(v[2]), num(v[3]))
    if tag == "E":
        return "Enum.%s.%s" % (v[1], v[2])
    if tag == "A":
        return "ASSETS.%s" % v[1]
    raise ValueError(v)


SKIP = {"name", "a0", "a1", "parent"}


def props(var, item, order):
    lines = []
    for key in order:
        if key in item:
            lines.append("\t%s.%s = %s" % (var, key, value(item[key])))
    for key, v in item.items():
        if key not in SKIP and key not in order and not key.startswith("_"):
            lines.append("\t%s.%s = %s" % (var, key, value(v)))
    return lines


BEAM_ORDER = ["Texture", "TextureMode", "TextureLength", "TextureSpeed", "FaceCamera", "Segments", "CurveSize0", "CurveSize1",
              "Width0", "Width1", "Color", "Transparency", "LightEmission", "LightInfluence", "Brightness", "ZOffset"]
EMITTER_ORDER = ["Texture", "FlipbookLayout", "FlipbookMode", "FlipbookFramerate", "FlipbookStartRandom", "Rate", "Lifetime",
                 "Speed", "SpreadAngle", "Acceleration", "Drag", "Size", "Squash", "Transparency", "Color", "Rotation", "RotSpeed",
                 "Orientation", "LightEmission", "LightInfluence", "Brightness", "ZOffset", "LockedToPart"]
TRAIL_ORDER = ["Texture", "TextureMode", "TextureLength", "Lifetime", "MinLength", "MaxLength", "FaceCamera", "Color",
               "Transparency", "WidthScale", "LightEmission", "LightInfluence", "Brightness"]


def used_assets(el):
    names = []
    for group in ("beams", "emitters", "trails"):
        for item in el[group]:
            t = item.get("Texture")
            if isinstance(t, tuple) and t[1] not in names:
                names.append(t[1])
    return names


HEADER = """-- GENERATED by tools/vfx/realm6_build_luau.py from tools/vfx/realm6_elements.py. Do not edit: change the spec, rerun.
"""

PRELUDE = """local ServerStorage = game:GetService("ServerStorage")
local bench = workspace:FindFirstChild("AuraWorkbench") or ServerStorage:FindFirstChild("DevStage") and ServerStorage.DevStage:FindFirstChild("AuraWorkbench")
assert(bench, "Realm6: no AuraWorkbench in Workspace or ServerStorage.DevStage")
local root = bench.AuraDummy.HumanoidRootPart
local humanoid = bench.AuraDummy:FindFirstChildOfClass("Humanoid")
local GROUND = -(root.Size.Y / 2 + humanoid.HipHeight) -- y = 0 in the spec: the ground under the root part
"""


def element_body(el):
    lines = []
    pre = el["prefix"]
    lines.append("do -- %s" % el["name"])
    lines.append('\tlocal PREFIX = "%s"' % pre)
    lines.append("\tfor _, c in root:GetChildren() do")
    lines.append("\t\tif string.sub(c.Name, 1, #PREFIX) == PREFIX then")
    lines.append("\t\t\tc:Destroy()")
    lines.append("\t\tend")
    lines.append("\tend")
    lines.append("\tlocal A = {}")
    for a in el["attachments"]:
        p, x, y = a["pos"], a["x"], a["y"]
        lines.append('\tA["%s"] = Instance.new("Attachment")' % a["name"])
        lines.append('\tA["%s"].Name = "%s"' % (a["name"], a["name"]))
        lines.append('\tA["%s"].CFrame = CFrame.fromMatrix(Vector3.new(%s, %s + GROUND, %s), Vector3.new(%s, %s, %s), Vector3.new(%s, %s, %s))'
                     % (a["name"], num(p[0]), num(p[1]), num(p[2]), num(x[0]), num(x[1]), num(x[2]), num(y[0]), num(y[1]), num(y[2])))
        lines.append('\tA["%s"].Parent = root' % a["name"])
    for b in el["beams"]:
        lines.append("\tdo")
        lines.append('\t\tlocal b = Instance.new("Beam")')
        lines.append('\t\tb.Name = "%s"' % b["name"])
        lines.append('\t\tb.Attachment0 = A["%s"]' % b["a0"])
        lines.append('\t\tb.Attachment1 = A["%s"]' % b["a1"])
        lines.extend("\t" + l for l in props("b", b, BEAM_ORDER))
        lines.append("\t\tb.Parent = root")
        lines.append("\tend")
    for t in el["trails"]:
        lines.append("\tdo")
        lines.append('\t\tlocal t = Instance.new("Trail")')
        lines.append('\t\tt.Name = "%s"' % t["name"])
        lines.append('\t\tt.Attachment0 = A["%s"]' % t["a0"])
        lines.append('\t\tt.Attachment1 = A["%s"]' % t["a1"])
        lines.extend("\t" + l for l in props("t", t, TRAIL_ORDER))
        lines.append("\t\tt.Parent = root")
        lines.append("\tend")
    for em in el["emitters"]:
        lines.append("\tdo")
        lines.append('\t\tlocal e = Instance.new("ParticleEmitter")')
        lines.append('\t\te.Name = "%s"' % em["name"])
        lines.extend("\t" + l for l in props("e", em, EMITTER_ORDER))
        lines.append('\t\te.Parent = A["%s"]' % em["parent"])
        lines.append("\tend")
    lines.append('\tprint(("Realm6 %s: %%d attachments, %%d beams, %%d emitters, %%d trails"):format(%d, %d, %d, %d))'
                 % (el["name"], len(el["attachments"]), len(el["beams"]), len(el["emitters"]), len(el["trails"])))
    lines.append("end")
    return lines


def assets_block(names):
    lines = ["local ASSETS = {"]
    missing = []
    for n in names:
        aid = E.TEXTURES[n][1]
        lines.append('\t%s = "rbxassetid://%s", -- %s' % (n, aid if aid else 0, E.TEXTURES[n][0] or "an existing Creator Store image"))
        if not aid:
            missing.append(n)
    lines.append("}")
    lines.append("for name, id in ASSETS do")
    lines.append('\tif id == "rbxassetid://0" then')
    lines.append('\t\terror("Realm6: " .. name .. " is not uploaded yet (approve the image, upload it, put its id in tools/vfx/realm6_elements.py, rerun realm6_build_luau.py)")')
    lines.append("\tend")
    lines.append("end")
    return lines, missing


def write_element(el):
    names = used_assets(el)
    block, missing = assets_block(names)
    doc = [
        "-- Realm 6 (Immortal) %s: run in Studio's command bar (Edit). Builds this element's authored Attachments, Beams," % el["name"],
        "-- ParticleEmitters and Trails on the AuraWorkbench dummy's HumanoidRootPart (in Workspace or ServerStorage.DevStage),",
        "-- replacing its earlier instances (names starting \"%s\"). Then inspect each piece on its own; Save to File." % el["prefix"],
    ]
    if el.get("motion"):
        doc.append("-- Its Trails need Realm6Motion (src/client/Auras) running in Play to move their attachments.")
    src = HEADER + "\n".join(doc) + "\n" + "\n".join(block) + "\n" + PRELUDE + "\n".join(element_body(el)) + "\n"
    path = os.path.join(OUT, "build_%s.lua" % el["name"].lower())
    with open(path, "w") as f:
        f.write(src)
    return path, missing


def write_all(els):
    names = []
    for el in els:
        for n in used_assets(el):
            if n not in names:
                names.append(n)
    block, missing = assets_block(names)
    body = []
    for el in els:
        body.extend(element_body(el))
    src = (HEADER + "-- Realm 6 (Immortal): every Studio-built element in order (%s). Run in the command bar (Edit).\n"
           % ", ".join(e["name"] for e in els) + "\n".join(block) + "\n" + PRELUDE + "\n".join(body) + "\n")
    path = os.path.join(OUT, "build_all.lua")
    with open(path, "w") as f:
        f.write(src)
    return path, missing


def write_motion(els):
    V = E.VORTEX
    movers = []
    for el in els:
        for m in el.get("motion", []):
            movers.append('\t\t{ Kind = "Helix", A = "%s", B = "%s", Trail = "%s", Arm = %d, Phase = %s, Width = %s },'
                          % (m["a"], m["b"], m["trail"], m["arm"], num(m["phase"]), num(m["width"])))
    src = HEADER + """-- Realm6MotionConfig: what Realm6Motion drives on the Studio-built Realm 6 elements: the attachments it moves (the vortex
-- comets up their helix arms). Studs from the ground under the root part (x right, y up, z behind), seconds, radians.
return {
\tVortex = { Arms = %d, Turns = %s, Y0 = %s, Y1 = %s, R0 = %s, R1 = %s, Period = %s },
\tMovers = {
%s
\t},
\tCullDistance = 140, -- other players' movers stop past this many studs from the camera
}
""" % (V["arms"], num(V["turns"]), num(V["y0"]), num(V["y1"]), num(V["r0"]), num(V["r1"]), num(V["period"]),
       "\n".join(movers))
    with open(MOTION, "w") as f:
        f.write(src)
    return MOTION


def main():
    os.makedirs(OUT, exist_ok=True)
    els = [E.ELEMENTS[n]() for n in E.ORDER]
    for el in els:
        path, missing = write_element(el)
        print(os.path.relpath(path, ROOT), "(waiting for: %s)" % ", ".join(missing) if missing else "(ready)")
    path, missing = write_all(els)
    print(os.path.relpath(path, ROOT))
    print(os.path.relpath(write_motion(els), ROOT))


main()
