"""The Murim High Ponytail, third design, stage 2: the secondary forms (run inside Blender).

The primary forms (v3.py) are the guides; the hair itself is the locks laid along them, every lock
designed in the tables below (its own path, width, thickness and length), none generated by a loop
of random copies. Layering, from under to over: the mane base (v3's mane, coarse, so nothing
shows between locks), the nape, the crown locks sweeping into the tie, the side curtains, the
chest locks, the bangs; the tail and the burst out of the tie; a few deliberate flyaways.

Each lock is a lens-sectioned clump (hair_kit.clump): its width lies along the head, it opens from
its root, is widest about a third of the way, and comes to a point. Game mesh: four sides; high
detail: fourteen sides with strand grooves, for the bake.
"""
import math

from mathutils import Vector

import hair_kit as H
import v3

K = H.K
V = Vector
DEG = math.pi / 180
TIE = v3.TIE

# the game mesh's and the high-detail version's lock resolution: sections, segment length
# the game mesh's lock sections and segment lengths per group: six sides where the camera looks
# most (rounded clumps, not folded plates), five on the tail and the burst, four on the thin chest
# locks; the high-detail source is the same everywhere
RES = {"low": {"bangs": (6, 0.3), "crown": (6, 0.34), "curtains": (6, 0.3), "chest": (4, 0.21), "burst": (5, 0.22),
               "tail": (5, 0.42), "mane": (14, 4)},
       "hi": {"sides": 14, "step": 0.025, "mane": (14, 4)}}   # the mane base is smooth: its source is
                                                                                  # itself, so its normals bake flat


def ridge_for(seed):
    """Strand grooves along a high-detail lock (each lock its own phase)."""
    ph = (seed * 2.399) % (2 * math.pi), (seed * 1.618) % (2 * math.pi)

    def ridge(k, n, ang):
        u = k / (n - 1)
        return (0.0022 * abs(math.sin(ang * 11 + ph[0] + 2 * u)) + 0.005 * abs(math.sin(ang * 3 + ph[1] + 5 * u)) ** 0.7
                + 0.0015) * (1 - H.smoothstep(0.82, 1.0, u))
    return ridge


class Locks:
    def __init__(self, res):
        self.r = RES[res]
        self.hi = res == "hi"
        self.n = 0

    def lock(self, mesh, pts, w, th, group, swell=0.35, root=0.85, flat=None):
        self.n += 1
        sides, step = (self.r["sides"], self.r["step"]) if self.hi else self.r[group]
        H.clump(mesh, [V(p) for p in pts], w, th, step, sides, 0,
                ridge_for(self.n) if self.hi else None, swell=swell, root=root, flat=flat)


def mirror(pts):
    return [(-x, y, z) for x, y, z in pts]


# ---------- the bangs ----------
# per side, from the parting outward: (points for the wearer's left, width, thickness). The right
# side is its own design, not a mirror: its locks run a little shorter and its outer lock flicks
# less, so the face isn't framed by a copy.
BANGS_LEFT = [
    ([(0.04, -0.2, 3.3), (0.12, -0.66, 3.28), (0.17, -0.77, 3.0), (0.2, -0.74, 2.56)], 0.2, 0.07),      # between the eyes
    ([(0.07, -0.21, 3.31), (0.19, -0.67, 3.28), (0.26, -0.78, 2.99), (0.31, -0.75, 2.71)], 0.12, 0.05),
    ([(0.12, -0.17, 3.31), (0.34, -0.64, 3.27), (0.45, -0.76, 3.0), (0.52, -0.72, 2.68)], 0.22, 0.07),  # to the eye
    ([(0.16, -0.16, 3.32), (0.41, -0.62, 3.28), (0.56, -0.73, 3.04), (0.63, -0.69, 2.81)], 0.14, 0.05),
    ([(0.2, -0.14, 3.3), (0.52, -0.58, 3.23), (0.67, -0.69, 2.98), (0.78, -0.62, 2.76)], 0.22, 0.07),   # out to the temple
    ([(0.24, -0.1, 3.3), (0.58, -0.52, 3.21), (0.75, -0.6, 3.0), (0.88, -0.5, 2.9)], 0.13, 0.05),
]
BANGS_RIGHT = [
    ([(0.04, -0.2, 3.3), (0.13, -0.66, 3.28), (0.18, -0.77, 3.0), (0.23, -0.74, 2.6)], 0.19, 0.07),
    ([(0.08, -0.21, 3.31), (0.2, -0.67, 3.28), (0.28, -0.78, 2.99), (0.34, -0.75, 2.75)], 0.12, 0.05),
    ([(0.12, -0.17, 3.31), (0.35, -0.64, 3.27), (0.46, -0.76, 3.0), (0.51, -0.72, 2.72)], 0.22, 0.07),
    ([(0.17, -0.16, 3.32), (0.42, -0.62, 3.28), (0.57, -0.73, 3.04), (0.62, -0.7, 2.84)], 0.14, 0.05),
    ([(0.2, -0.14, 3.3), (0.52, -0.58, 3.23), (0.67, -0.69, 2.98), (0.76, -0.63, 2.78)], 0.22, 0.07),
    ([(0.25, -0.1, 3.3), (0.58, -0.52, 3.21), (0.74, -0.6, 3.01), (0.84, -0.53, 2.93)], 0.12, 0.05),
]


def bangs(L, m):
    for pts, w, th in BANGS_LEFT:
        L.lock(m, pts, w, th, "bangs")
    for pts, w, th in BANGS_RIGHT:
        L.lock(m, mirror(pts), w, th, "bangs")


# ---------- the side curtains ----------
# per side, round the head from its front corner: (azimuth, start elevation, cheek flare, tip
# height, width, thickness, tip flick out). Each primary lobe split into a broad lock and a finer one
# laid over it, a little behind, shorter, flicking further out.
CURTAINS = {
    1: [(60, 34, 0.93, 1.92, 0.32, 0.1, 0.0), (72, 32, 0.96, 2.16, 0.2, 0.06, 0.03),
        (92, 32, 0.96, 1.98, 0.34, 0.1, 0.0), (104, 30, 0.99, 2.2, 0.2, 0.06, 0.04),
        (124, 30, 0.92, 2.1, 0.32, 0.1, 0.0), (138, 28, 0.94, 2.3, 0.2, 0.06, 0.03)],
    -1: [(60, 34, 0.92, 1.96, 0.32, 0.1, 0.0), (73, 32, 0.95, 2.18, 0.2, 0.06, 0.03),
         (92, 32, 0.95, 2.02, 0.34, 0.1, 0.0), (106, 30, 0.98, 2.24, 0.2, 0.06, 0.04),
         (124, 30, 0.92, 2.12, 0.32, 0.1, 0.0), (139, 28, 0.93, 2.32, 0.19, 0.06, 0.03)],
}


def curtains(L, m, tree):
    for side, locks in CURTAINS.items():
        for az, el, flare, tipz, w, th, flick in locks:
            a = az * DEG
            p, n = H.on_head(tree, side * a, el * DEG)

            def ring(r, z, a=a, side=side):
                return V((side * math.sin(a) * r, -math.cos(a) * r, z))
            # emerging narrow from under the crown sweep, close to the head, then falling
            L.lock(m, [p - n * 0.02, ring(0.76, 2.9), ring(flare * 0.9, 2.46), ring(0.82 + flick, tipz)], w, th * 0.8, "curtains",
                   swell=0.4, root=0.45)


# ---------- the chest locks ----------
# per side: the long lock framing the face onto the chest, and a thinner one splitting off it at the
# jaw, curving out and ending higher. The wearer's left runs a little longer.
CHEST = {
    1: [([(0.42, -0.5, 3.12), (0.66, -0.68, 2.92), (0.74, -0.74, 2.5), (0.74, -0.72, 2.0), (0.7, -0.66, 1.55), (0.72, -0.62, 1.08)], 0.12, 0.065),
        ([(0.46, -0.48, 3.1), (0.7, -0.66, 2.9), (0.78, -0.71, 2.45), (0.82, -0.68, 2.0), (0.88, -0.6, 1.62)], 0.07, 0.04)],
    -1: [([(0.42, -0.5, 3.12), (0.66, -0.68, 2.92), (0.74, -0.74, 2.5), (0.73, -0.72, 2.0), (0.69, -0.66, 1.6), (0.7, -0.62, 1.2)], 0.12, 0.065),
         ([(0.46, -0.48, 3.1), (0.7, -0.66, 2.9), (0.78, -0.71, 2.45), (0.83, -0.67, 2.05), (0.9, -0.6, 1.72)], 0.07, 0.04)],
}


def chest(L, m):
    for side, locks in CHEST.items():
        for pts, w, th in locks:
            L.lock(m, [(side * x, y, z) for x, y, z in pts], w, th, "chest", swell=0.28, root=0.8)


# ---------- the crown ----------
# the hair drawn up into the tie: each lock rises from low on the head (behind the bangs at the
# front, from the hairline above the ear at the sides, from the nape's top at the back), emerging
# narrow from under the curtains and the nape, widening as it sweeps up, and gathering under the
# clasp. (azimuth, elevation of its root, bulge, width): the front ones narrowest, the sides broadest.
CROWN = [(0, 52, 0.15, 0.24), (26, 44, 0.17, 0.26), (-26, 44, 0.17, 0.26), (58, 16, 0.2, 0.3), (-58, 16, 0.2, 0.3),
         (92, 2, 0.21, 0.32), (-92, 2, 0.21, 0.32), (128, -4, 0.2, 0.3), (-128, -4, 0.2, 0.3)]


def crown(L, m, tree):
    for az, el, bulge, w in CROWN:
        p, n = H.on_head(tree, az * DEG, el * DEG)
        root = p - n * 0.02
        mid = (root + TIE) / 2
        mid = mid + (mid - v3.C).normalized() * bulge + V((0, 0, 0.03))
        end = TIE + (root - TIE).normalized() * 0.02 - V((0, 0, 0.05))   # into the tie, under the clasp
        L.lock(m, [root, mid, end], w, 0.07, "crown", swell=0.5, root=0.35)


# ---------- the nape ----------
# under the tail at the back of the head: locks hanging to the top of the back. (azimuth, tip height, width)
NAPE = [(148, 2.02, 0.3), (166, 1.9, 0.32), (184, 1.86, 0.32), (202, 1.92, 0.3), (218, 2.04, 0.28)]


def nape(L, m, tree):
    for az, tipz, w in NAPE:
        a = az * DEG
        p, n = H.on_head(tree, a, 8 * DEG)
        low, n2 = H.on_head(tree, a, -30 * DEG)
        out = V((low.x, low.y, 0)).normalized()
        L.lock(m, [p - n * 0.02, low + n2 * 0.16, V((low.x, low.y, tipz)) + out * 0.22], w, 0.08, "curtains", swell=0.35, root=0.9)


# ---------- the burst out of the tie ----------
# the tied hair's ends springing up above the clasp and curling back: (direction, length, width)
BURST = [((0.15, -0.35, 1.0), 0.4, 0.21), ((0.6, 0.15, 1.0), 0.44, 0.2), ((-0.55, 0.2, 1.0), 0.42, 0.2),
         ((-0.05, 0.7, 0.75), 0.36, 0.19)]


def burst(L, m):
    for d, length, w in BURST:
        d = V(d).normalized()
        tip = TIE + d * length + V((0, 0.16, -0.14))     # curling back over
        up = V((0, 0, 1)) if abs(d.z) < 0.95 else V((0, 1, 0))
        L.lock(m, [TIE - V((0, 0, 0.04)), TIE + d * (length * 0.6), tip], w, 0.065, "burst", swell=0.32, root=0.75,
               flat=d.cross(up).normalized() if d.cross(up).length > 1e-3 else V((1, 0, 0)))


# ---------- the tail ----------
# the guide: up out of the tie, over, and down the back in an S, swinging a little to the wearer's
# left at the end
GUIDE = [TIE + V((0, 0.02, -0.04)), V((0.0, 0.42, 3.62)), V((0.0, 0.64, 3.65)), V((0.0, 0.92, 3.42)), V((0.05, 1.02, 2.95)),
         V((0.02, 1.04, 2.35)), V((-0.07, 0.96, 1.75)), V((0.0, 0.92, 1.2)), V((0.1, 0.9, 0.6))]   # close behind the head
# the clumps, in two layers: (place across at the flare, depth off the guide, tip height, width, flick out)
TAIL = [(0.0, 0.12, 0.52, 0.34, 0.0), (0.27, 0.07, 0.78, 0.3, 0.05), (-0.3, 0.07, 0.86, 0.3, -0.05),
        (0.52, 0.0, 1.14, 0.24, 0.12), (-0.5, 0.0, 1.04, 0.24, -0.12),
        (0.08, -0.1, 0.92, 0.3, 0.0), (0.32, -0.12, 1.36, 0.22, 0.08), (-0.29, -0.12, 1.3, 0.22, -0.08)]


def tail(L, m):
    guide = K.resample(GUIDE, 0.02)
    n = len(guide)
    for x0, dy, tipz, w, flick in TAIL:
        pts = []
        for k, g in enumerate(guide):
            u = k / (n - 1)
            if g.z < tipz and u > 0.5:
                break
            spread = H.smoothstep(0.08, 0.45, u) * (1.0 + 0.3 * H.smoothstep(0.6, 1.0, u))
            pts.append(g + V((x0 * spread + flick * H.smoothstep(0.7, 1.0, u), dy * H.smoothstep(0.05, 0.3, u), 0)))
        pts.append(V((pts[-1].x + flick * 0.5, pts[-1].y + 0.02, tipz)))
        L.lock(m, pts[::max(1, len(pts) // 14)] + [pts[-1]], w, 0.1, "tail", swell=0.32, root=0.6, flat=V((1, 0, 0)))


# ---------- flyaways ----------
FLY = [[(0.3, 1.16, 2.8), (0.62, 1.2, 2.35), (0.86, 1.08, 1.98), (0.92, 0.98, 1.84)],      # off the tail's left
       [(-0.62, -0.25, 3.02), (-0.95, -0.32, 2.78), (-1.04, -0.36, 2.48)]]                 # off the right curtain


def flyaways(L, m):
    for pts in FLY:
        L.lock(m, pts, 0.04, 0.014, "chest", swell=0.2, root=1.0)


def build(tree, res, mat=None):
    """Stage 2 into MURIM_HAIR_V3: the mane base and every lock group, one object per group
    (V3L_<Group>_<res>)."""
    import bpy
    coll = K.collection(v3.COLLECTION + "_" + res.upper())
    for o in list(coll.objects):
        me = o.data
        bpy.data.objects.remove(o, do_unlink=True)
        if me and me.users == 0:
            bpy.data.meshes.remove(me)
    L = Locks(res)
    mat = mat or K.mat_flat("V3_Clay", (0.22, 0.22, 0.23), 0.6)
    mats = mat if isinstance(mat, dict) else {}
    out = []

    def obj(name, mesh, key, shell=0):
        # only the mane is welded (its crown point); locks are built closed and must stay separate parts
        o = mesh.object("V3L_%s_%s" % (name, res), coll, [mats.get(key, mat) if mats else mat], weld=1e-5 if name == "Mane" else 0)
        if shell:
            K.solidify(o, shell)
        out.append(o)
    cols, rows = L.r["mane"]
    obj("Mane", v3.mane(tree, cols, rows), "hair", 0.02)
    # not built: the nape (hidden under the tail; the mane base covers there) and the flyaways
    # (at this size they read as twigs, not hair)
    for name, fn, key in (("Crown", lambda m: crown(L, m, tree), "hair"),
                          ("Curtains", lambda m: curtains(L, m, tree), "hair"), ("Chest", lambda m: chest(L, m), "hair"),
                          ("Bangs", lambda m: bangs(L, m), "hair"), ("Burst", lambda m: burst(L, m), "hair"),
                          ("Tail", lambda m: tail(L, m), "tail")):
        m = K.Mesh()
        fn(m)
        obj(name, m, key)
    return out


# ---------- the ornament and the ribbon (stage 3) ----------
from ponytail import plate  # noqa: E402  (a closed plate with a properly triangulated outline)

TIE_AXIS = (V((0.0, 0.42, 3.62)) - (TIE + V((0, 0.02, -0.04)))).normalized()   # the hair leaves the tie upward
CROWN_FACE = V((0, -0.8, 0.6)).normalized()
CROWN_UP = V((0, 0.6, 0.8)).normalized()
CROWN_AT = TIE + V((0, -0.19, 0.1))


def clasp(m, hi):
    """The silver clasp gathering the tie: a band round it; at its front a pointed crown, its tallest
    point over the red gem; at its back a diamond clasp over the ribbon's knot."""
    side = TIE_AXIS.cross(V((0, 1, 0))).normalized()
    nrm = TIE_AXIS.cross(side).normalized()
    K.torus(m, TIE + TIE_AXIS * 0.02, side, nrm, 0.16, 0.16, 0.044, 40 if hi else 16, 10 if hi else 6, 0)
    # the crown: a third larger than first drawn, raised clear of the hair round the tie
    outline = [(x * 1.35, y * 1.35) for x, y in [(-0.13, 0.0), (-0.155, 0.1), (-0.09, 0.07), (-0.05, 0.16), (0.0, 0.26),
                                                 (0.05, 0.16), (0.09, 0.07), (0.155, 0.1), (0.13, 0.0), (0.0, -0.04)]]
    plate(m, CROWN_AT, V((1, 0, 0)), CROWN_UP, CROWN_FACE, outline, 0.03)
    plate(m, TIE + V((0, 0.2, 0.02)), V((-1, 0, 0)), V((0, -0.2, 1)).normalized(), V((0, 1, 0.2)).normalized(),
          [(0.0, 0.15), (0.11, 0.0), (0.0, -0.17), (-0.11, 0.0)], 0.03)


def gem(m, hi):
    c = CROWN_AT + CROWN_FACE * 0.035 + CROWN_UP * 0.115
    K.cylinder(m, c, CROWN_FACE, CROWN_UP, V((1, 0, 0)), 0.05, 0.035, 24 if hi else 8, 0)


def ribbons(m, hi):
    """The crimson ribbon tied at the back of the tie: a bow of two loops, two long tails down the
    middle of the tail's outer face with forked ends, and one streaming out to the wearer's left."""
    step = 0.03 if hi else 0.24
    cols = 6 if hi else 1

    def strip(pts, width, notch, wide):
        H.ribbon(m, K.resample([V(p) for p in pts], step), lambda k, n: width, wide, 0, notch=notch, cols=cols)
    knot = TIE + V((0, 0.19, -0.04))
    for s_ in (1, -1):
        pts = [knot, knot + V((0.12 * s_, 0.05, 0.1)), knot + V((0.26 * s_, 0.06, 0.06)), knot + V((0.24 * s_, 0.07, -0.06)),
               knot + V((0.08 * s_, 0.04, -0.05))]
        strip(pts, 0.11, 0.0, lambda kk: V((0, 0.3, 1)))
    guide = K.resample(GUIDE, 0.05)
    for s_, end in ((1, 1.3), (-1, 1.0)):
        pts = [knot + V((0.04 * s_, 0.0, -0.02))]
        for g in guide[4:]:
            if g.z < end:
                break
            pts.append(g + V((0.06 * s_ + 0.05 * math.sin(g.z * 3 + s_), 0.27, 0)))

        def wide(kk, s_=s_):
            a = 0.15 * math.sin(kk * 0.6 + s_)
            return V((math.cos(a), math.sin(a), 0))
        strip(pts, 0.12, 0.08, wide)
    pts = [knot + V((0.1, -0.02, 0.0)), (0.3, 0.62, 3.25), (0.58, 0.98, 3.0), (0.74, 1.24, 2.62), (0.8, 1.38, 2.15), (0.84, 1.44, 1.78)]

    def flutter(kk):
        a = 0.5 * math.sin(kk * 0.9)
        return V((0.15 * math.sin(a), math.cos(a) * 0.5, math.cos(a)))
    strip(pts, 0.11, 0.07, flutter)


def build_details(res, mats):
    """The ornament and the ribbon as their own objects (V3L_Clasp, V3L_Gem, V3L_Ribbons)."""
    coll = K.collection(v3.COLLECTION + "_" + res.upper())
    hi = res == "hi"
    out = []
    for name, fn, key, shell in (("Clasp", clasp, "silver", 0), ("Gem", gem, "gem", 0), ("Ribbons", ribbons, "silk", 0.012)):
        m = K.Mesh()
        fn(m, hi)
        o = m.object("V3L_%s_%s" % (name, res), coll, [mats[key], mats[key]], weld=0)
        if shell:
            K.solidify(o, shell)
        out.append(o)
    return out


